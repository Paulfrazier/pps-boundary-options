"""Model-v2 reports: TRADEOFFS.md per option (vs Scenario A v2 and Option 1-durable v2) and FRONTIER.md.
  python report_v2.py tradeoffs <option> [narrative.md]   -> out_v2/<option>/TRADEOFFS.md
  python report_v2.py frontier                            -> out_v2/FRONTIER.md
Every number is read from out_v2/<plan>/scorecard.json (cited per table)."""
import json, os, re, sys
import common as C, v2 as V2
OUT = os.path.join(C.SOLVER, 'out_v2')
def _plan_names():
    """Full display names from TRACKS.md "### Plans" (canonical; Paul may rename)."""
    t = open(os.path.join(C.SOLVER, '..', '..', 'TRACKS.md')).read()
    blk = t[t.index('### Plans'):]
    out = {}
    for line in blk.splitlines()[1:]:
        if line.startswith('### ') or line.startswith('## '):
            break
        m = re.match(r'\| `([^`]+)` \| ([^|]+) \|', line)
        if m:
            out[m.group(1)] = m.group(2).strip()
    return out
LABEL = _plan_names()
STAGED = set()   # runs read from <name>.staging (pre-promotion TRADEOFFS)
def sc(n):
    p = os.path.join(OUT, n + '.staging', 'scorecard.json') if n in STAGED else os.path.join(OUT, n, 'scorecard.json')
    return json.load(open(p)) if os.path.exists(p) else None
def lv(s, lev, k):
    v = s['levels'][lev].get(k)
    return v
def fmt(v, d=0):
    if v is None:
        return '–'
    if isinstance(v, float):
        return f'{v:,.{d}f}'
    return f'{v:,}' if isinstance(v, int) else str(v)
ROWS = [('avg_walk_mi', 'Avg walk (mi)', 3), ('pct_within_1.0mi', '% within 1 mi', 1), ('pct_within_1.5mi', '% within 1.5 mi', 1),
        ('kids_over_bus_threshold', 'Over the bus line', 0), ('kids_past_closer_school', 'Past a closer school', 0),
        ('kids_reassigned_vs_status_quo', 'Kids reassigned vs No changes', 0), ('kids_reassigned_vs_today', 'Kids reassigned vs Today', 0),
        ('schools_open', 'Schools open', 0), ('schools_in_range_non_exempt', 'Non-exempt schools in range, 2031-32', 0),
        ('dissimilarity_index', 'Segregation (dissimilarity) index', 3), ('n_split_feeders_es_to_ms', 'Split K-5 → 6-8 feeders', 0)]
def metric_table(names, lev):
    S = {n: sc(n) for n in names}
    out = [f'| {lev} | ' + ' | '.join(LABEL.get(n, n) for n in names) + ' |', '|---|' + '---|' * len(names)]
    for k, lab, d in ROWS:
        vals = [lv(S[n], lev, k) if S[n] else None for n in names]
        if all(v is None for v in vals):
            continue
        out.append(f'| {lab} | ' + ' | '.join(fmt(float(v) if isinstance(v, (int, float)) and d else v, d) for v in vals) + ' |')
    return '\n'.join(out)
def dur(d):   # scorecards name the all-years count by their horizon (2040-41 or 2035-36)
    return d.get('durable_through_2040_41', d.get('at_target_all_years_to_2035_36'))
def dur_table(names):
    S = {n: sc(n) for n in names}
    yrs = S[names[0]]['durability']['years']
    out = ['| Level | Plan | ' + ' | '.join(y[2:] for y in yrs) + ' | At target every year |', '|---|---|' + '---|' * (len(yrs) + 1)]
    for lev in C.LEVELS:
        for k, n in enumerate(names):
            if not S[n]:
                continue
            d = S[n]['durability']['levels'][lev]
            at = [d['at_target_zoned'][y] for y in yrs]
            out.append(f'| {lev + " (" + str(d["n_zoned_non_exempt"]) + ")" if k == 0 else ""} | {LABEL.get(n, n)} | '
                       + ' | '.join(str(a) for a in at) + f' | {dur(d)} |')
    return '\n'.join(out)
def meets_ref(n, ref='scenario_A'):
    a, b = sc(n)['durability'], sc(ref)['durability']
    short = []
    for lev in C.LEVELS:
        for y in a['years']:
            x, r = a['levels'][lev]['at_target_zoned'][y], b['levels'][lev]['at_target_zoned'][y]
            if x < r:
                short.append(f'{lev} {y}: {x} vs {r}')
    return short
def infeas(n):
    p = os.path.join(OUT, n + ('.staging' if n in STAGED else ''), 'infeasibility.json')
    return json.load(open(p)) if os.path.exists(p) else {}
def tradeoffs(n, narrative=''):
    names = ['scenario_A', 'option1_durable', n] if n != 'option1_durable' else ['scenario_A', 'option1_durable']
    if sc(n + '_msfeed_off'):
        names.insert(-1, n + '_msfeed_off')
    names = [x for x in names if sc(x)]
    s = sc(n)
    L = [f'# {LABEL.get(n, n)}: trade-offs (model v2)', '',

         f'Generated by `build/solver/report_v2.py` from `build/solver/out_v2/{{{",".join(names)}}}/scorecard.json`. '
         'Model v2 (see `build/solver/METHOD.md` §6 and `out_v2/CALIBRATION.md`). Every plan uses Scenario A\'s 9-12 lines. '
         '"At target" = zoned, non-exempt school between its floor (360 / 500 / 1,100) and its capacity (PPS 2025-26 school '
         'profiles), each school sized by its own PSU forecast for the year. Plan names follow TRACKS.md "Plans"; '
         '`*_msfeed_off` = the earlier v2 solve of the same plan without the feeder rules.', '']
    if narrative:
        L += [narrative.strip(), '']
    sh = meets_ref(n)
    L += ['## Schools at target, year by year', '', dur_table(names), '',
          ('**Meets or beats Scenario A\'s count every year at every level.**' if not sh else
           '**Falls short of Scenario A\'s count in:** ' + '; '.join(sh) + '.'), '']
    for lev in ('K-5', '6-8', '9-12'):
        L += [f'## {lev}', '', metric_table(names, lev), '']
        if lev == '9-12':
            L += ['| Middle zones feeding one high school (%) | ' + ' | '.join(
                fmt(sc(x)['levels']['9-12'].get('pct_ms_feeders_to_one_hs'), 1) for x in names) + ' |', '']
    inf = infeas(n)
    if inf:
        L += ['## Size problems left in 2031-32 (infeasibility.json)', '', '```', json.dumps(inf, indent=1, default=str)[:3000], '```', '']
    if s.get('optional_schools'):
        L += ['## Schools the solver kept open / closed', '', '```', json.dumps(s['optional_schools'], indent=1), '```', '']
    open(os.path.join(OUT, n + ('.staging' if n in STAGED else ''), 'TRADEOFFS.md'), 'w').write('\n'.join(L))
    print('wrote', n)
FRONT = ['scenario_A', 'frontier_k17', 'frontier_k19', 'frontier_k21', 'option1_durable']
def frontier(narrative=''):
    pts = [n for n in FRONT if sc(n)]
    L = ['# Walkability vs durability: the frontier (model v2)', '',
         'Every point uses Scenario A\'s schools, DLI placements and 9-12 lines, and the same hard rule: at least as many '
         'schools at target as Scenario A in every year 2031-32 → 2040-41. What changes is how hard the solver pushes '
         'for schools that stay at target in **all ten years**: no reward (k17), a required minimum (k19, k21), or '
         'option1_durable\'s reward of 3,000 kid-miles per durable school. Numbers from '
         '`build/solver/out_v2/<point>/scorecard.json`; generated by `report_v2.py frontier`.', '']
    if narrative:
        L += [narrative.strip(), '']
    for lev in ('K-5', '6-8'):
        L += [f'## {lev}', '', '| Plan | At target every year | Avg walk (mi) | % within 1 mi | Over the bus line | '
              'Past a closer school | Kids reassigned vs No changes | Size shortfall left in 2031-32 (kids) |', '|---|---|---|---|---|---|---|---|']
        rows = []
        for n in pts:
            s_ = sc(n); m = s_['levels'][lev]; d = s_['durability']['levels'][lev]
            comps = (infeas(n).get('solver_slack') or {}).get(lev, []) if n != 'scenario_A' else []
            slack = sum(v for c in comps for k, v in c.items() if k.endswith((':lo', ':hi')))
            rows.append((n, dur(d), m['avg_walk_mi'], m['pct_within_1.0mi'], m['kids_over_bus_threshold'],
                         m['kids_past_closer_school'], m['kids_reassigned_vs_status_quo']))
            L.append(f'| {LABEL.get(n, n)} | {dur(d)} of {d["n_zoned_non_exempt"]} | {m["avg_walk_mi"]:.3f} | '
                     f'{m["pct_within_1.0mi"]:.1f} | {m["kids_over_bus_threshold"]:,.0f} | {m["kids_past_closer_school"]:,.0f} | '
                     f'{m["kids_reassigned_vs_status_quo"]:,.0f} | {"–" if n == "scenario_A" else (round(slack, 1) if slack else 0)} |')
        ours = [r for r in rows if r[0] != 'scenario_A']
        if len(ours) >= 2:
            a0, a1 = ours[0], ours[-1]
            dn = a1[1] - a0[1]
            if dn > 0:
                L += ['', f'**What each extra {lev} school at target every year costs** (from {LABEL.get(a0[0])} to {LABEL.get(a1[0])}, '
                      f'+{dn} schools): about {(a1[4] - a0[4]) / dn:+,.0f} kids over the bus line, '
                      f'{(a1[5] - a0[5]) / dn:+,.0f} kids past a closer school, {(a1[2] - a0[2]) / dn * 5280:+,.0f} ft '
                      f'of average walk and {(a1[6] - a0[6]) / dn:+,.0f} kids reassigned, per extra school.']
        L.append('')
    open(os.path.join(OUT, 'FRONTIER.md'), 'w').write('\n'.join(L))
    print('wrote FRONTIER.md')


if __name__ == '__main__':
    if sys.argv[1] == 'frontier':
        frontier(open(sys.argv[2]).read() if len(sys.argv) > 2 else '')
    if '--staging' in sys.argv:
        sys.argv.remove('--staging')
        STAGED.add(sys.argv[2])
    if sys.argv[1] == 'tradeoffs':
        nar = open(sys.argv[3]).read() if len(sys.argv) > 3 else ''
        tradeoffs(sys.argv[2], nar)
