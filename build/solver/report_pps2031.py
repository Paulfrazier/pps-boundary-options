"""TRADEOFFS.md for the pps2031-horizon reruns (Paul 2026-10-12 ~15:15, item 7).
  python report_pps2031.py <run> [narrative.md] [--staging]
Compares <run> with PPS Scenario A and option1_durable_msfeed_off (the walkable baseline), all scored on horizon
pps2031.  Every number is read from out_v2/<plan>/scorecard.json and schools.csv (cited in the header)."""
import json, os, sys
import pandas as pd
import common as C
from report_v2 import LABEL

OUT = os.path.join(C.SOLVER, 'out_v2')
STAGED = set()
REF = ['scenario_A', 'option1_durable_msfeed_off']
DLABEL = dict(LABEL)
DLABEL['option1_durable_msfeed_off'] = 'Walkable baseline (option1_durable_msfeed_off)'


def d(n):
    return os.path.join(OUT, n + ('.staging' if n in STAGED else ''))


def sc(n):
    return json.load(open(os.path.join(d(n), 'scorecard.json')))


def f(v, k=0):
    if v is None:
        return '–'
    return f'{v:,.{k}f}' if isinstance(v, (int, float)) else str(v)


def shortfalls(n):
    s = pd.read_csv(os.path.join(d(n), 'schools.csv'))
    s = s[(s['below_floor']) | (s['above_ceiling'])]
    out = []
    for r in s.sort_values('short_by', ascending=False).itertuples():
        if r.below_floor:
            out.append(f'{r.school} −{r.short_by:.0f}' if r.short_by >= 0.5 else f'{r.school} −{r.short_by:.1f}')
            out[-1] += ' (program-only)' if r.program_only else ''
        else:
            out.append(f'{r.school} +{r.over_by:.0f} over capacity')
    return out


def moved_vs_A(n, lev='9-12'):
    """kids (2031-32 basis) whose school at `lev` differs from Scenario A's"""
    import metrics as MX
    a = pd.read_parquet(os.path.join(d('scenario_A'), f'assign_{lev}.parquet'))['school'].values
    b = pd.read_parquet(os.path.join(d(n), f'assign_{lev}.parquet'))['school'].values
    cfg = C.load_config(os.path.join(C.SOLVER, 'configs', 'v2', f'{n}.json')) if os.path.exists(
        os.path.join(C.SOLVER, 'configs', 'v2', f'{n}.json')) else C.load_config(os.path.join(C.SOLVER, 'configs', 'v2', 'option1_durable.json'))
    K = MX.level_kids(cfg, '2031')[lev]
    return float(K[a != b].sum())


def es_hs_splits(n):
    """elementary zones whose 9-12-band kids go to more than one high school (>=5 kids on a side)"""
    import metrics as MX
    k5 = pd.read_parquet(os.path.join(d(n), 'assign_K-5.parquet'))['school'].values
    hs = pd.read_parquet(os.path.join(d(n), 'assign_9-12.parquet'))['school'].values
    cp = os.path.join(C.SOLVER, 'configs', 'v2', f'{n}.json')
    K = MX.level_kids(C.load_config(cp), '2031')['9-12']
    df = pd.DataFrame({'e': k5, 'h': hs, 'k': K}).groupby(['e', 'h'])['k'].sum().reset_index()
    out = []
    for e, g in df.groupby('e'):
        g = g[g['k'] >= 5].sort_values('k', ascending=False)
        if len(g) > 1:
            out.append(f'{e} → ' + ', '.join(f'{r.h} {r.k:.0f}' for r in g.itertuples()))
    return '; '.join(out) or 'none'


def tradeoffs(n, narrative='', refs=None):
    names = (refs or REF) + [n]
    S = {x: sc(x) for x in names}
    D0 = S[n]['durability']
    yrs, req = D0['years'], set(D0['required_years'])
    L = [f'# {LABEL.get(n, n)}: trade-offs (model v2, PPS horizon)', '',
         f'Generated by `build/solver/report_pps2031.py` from `build/solver/out_v2/{{{",".join(names)}}}/scorecard.json` '
         'and `schools.csv`. Model v2 (`build/solver/METHOD.md` §6, §7; `out_v2/CALIBRATION.md`). All plans here use '
         'Scenario A\'s schools and programs' + ('' if n == 'option1_full' else ' and 9-12 lines')
         + (' (this plan redraws the 9-12 lines; the others keep Scenario A\'s)' if n == 'option1_full' else '') + ' and are scored on the same horizon: **required** = meet or beat Scenario A\'s '
         'count of schools at target every year 2027-28 → 2031-32 (PPS Family Guide p. 1: "Estimates cover 2027-28 through '
         '2031-32" [PPS]); 2032-33 → 2035-36 **reported only** (last year of PSU\'s per-school Table 5.5 [PPS/PSU]); nothing '
         'past 2035-36. "At target" = zoned, non-exempt school between its floor (360 K-5 / 500 K-8 and '
         '6-8 / 1,100 9-12) and its capacity (PPS 2025-26 school profiles), each sized by its own PSU forecast for the year '
         '[inferred: our model on PPS/PSU numbers].' + (' The walkable baseline is the earlier v2 solve with no feeder rules and '
         'no nesting; its lines were solved for the old 2031-32 → 2040-41 window and are re-scored here.'
         if 'option1_durable_msfeed_off' in names else ''), '']
    if narrative:
        L += [narrative.strip(), '']
    # durability
    L += ['## Schools at target, year by year', '',
          '`*` = required year. Counts from `durability.levels[*].at_target_zoned`.', '',
          '| Level | Plan | ' + ' | '.join(y[2:] + ('*' if y in req else '') for y in yrs) +
          ' | All required years | All years to 2035-36 |', '|---|---|' + '---|' * (len(yrs) + 2)]
    for lev in C.LEVELS:
        for k, x in enumerate(names):
            dl = S[x]['durability']['levels'][lev]
            L.append(f'| {lev + " (" + str(dl["n_zoned_non_exempt"]) + ")" if k == 0 else ""} | {DLABEL.get(x, x)} | '
                     + ' | '.join(str(dl['at_target_zoned'][y]) for y in yrs)
                     + f' | {dl["at_target_all_required_years"]} | {dl["at_target_all_years_to_2035_36"]} |')
    L.append('')
    for x in names[1:]:
        ref = S[x]['durability'].get('reference') or {}
        sh = ref.get('short_in_required_years', [])
        L.append(f'- {DLABEL.get(x, x)}: ' + ('meets or beats Scenario A in every required year at every level.' if not sh
                 else 'short of Scenario A in ' + '; '.join(f'{s["level"]} {s["year"]} ({s["plan"]} vs {s["reference"]})'
                                                             for s in sh) + '.'))
    L.append('')
    # lines
    ROWS = [('avg_walk_mi', 'Avg walk (mi)', 3), ('pct_within_1.0mi', '% within 1 mi', 1),
            ('kids_past_closer_school', 'Past a closer school', 0), ('kids_over_bus_threshold', 'Over the bus line', 0),
            ('kids_reassigned_vs_status_quo', 'Kids reassigned vs PPS Status Quo', 0),
            ('schools_in_range_non_exempt', 'Non-exempt schools in range, 2031-32', 0),
            ('dissimilarity_index', 'Segregation (dissimilarity) index', 3)]
    L += ['## Walking, moves and feeders (2031-32 basis)', '',
          '| Level | Measure | ' + ' | '.join(DLABEL.get(x, x) for x in names) + ' |', '|---|---|' + '---|' * len(names)]
    for lev in C.LEVELS:
        for k, (key, lab, dd) in enumerate(ROWS):
            L.append(f'| {lev if k == 0 else ""} | {lab} | ' + ' | '.join(f(S[x]['levels'][lev].get(key), dd) for x in names) + ' |')
    L.append('| 9-12 | High schoolers reassigned vs PPS Scenario A | ' + ' | '.join(f(moved_vs_A(x)) for x in names) + ' |')
    L.append('| 9-12 | HS range, 2031-32 (largest − smallest; KPI < 350) | ' + ' | '.join(
        f(S[x]['levels']['9-12'].get('hs_range')) for x in names) + ' |')
    L.append('| 6-8 | K-5 zones split between middle schools (ES→MS splits) | ' + ' | '.join(
        f(S[x]['levels']['6-8'].get('n_split_feeders_es_to_ms')) for x in names) + ' |')
    L.append('| 9-12 | Middle zones feeding one high school (%) | ' + ' | '.join(
        f'{S[x]["levels"]["9-12"]["pct_ms_feeders_to_one_hs"]:.0f}% ({15 - S[x]["levels"]["9-12"]["n_split_feeders_ms_to_hs"]} of 15)'
        for x in names) + ' |')
    L += ['', 'Bus line = 1 mi K-5, 1.5 mi 6-8/9-12 (ORS 327.043 / PPS). Past a closer school = 0.25 mi margin, no new I-84/'
          'river crossing. Kids = neighborhood-program kids on the 2031-32 basis.', '']
    L += ['**Split feeders in this plan** (a destination counts at ≥5% and ≥5 kids):', '',
          '- Middle → high: ' + ('; '.join(f'{a} → {", ".join(f"{h} {v:.0f}" for h, v in dd.items())}'
                                          for a, dd in S[n]['levels']['9-12']['split_feeders_ms_to_hs'].items()) or 'none'),
          '- Elementary → middle: ' + ('; '.join(f'{a} → {", ".join(f"{h} {v:.0f}" for h, v in dd.items())}'
                                              for a, dd in S[n]['levels']['6-8']['split_feeders_es_to_ms'].items()) or 'none'),
          '- Elementary → high (high-school-age kids): ' + es_hs_splits(n), '']
    L += ['## 2031-32 size problems by school', '', '| Plan | Schools outside their range in 2031-32 (kids short of floor / over capacity) |', '|---|---|']
    for x in names:
        L.append(f'| {DLABEL.get(x, x)} | {", ".join(shortfalls(x)) or "none"} |')
    L += ['', 'Focus options are not counted. Program-only buildings (no neighborhood area) are sized by program placement, not lines.', '']
    p = os.path.join(d(n), 'infeasibility.json')
    if os.path.exists(p):
        inf = json.load(open(p))
        L += ['Solver slack left (`infeasibility.json` → `solver_slack`, kids): ' + json.dumps(inf.get('solver_slack')), '']
    open(os.path.join(d(n), 'TRADEOFFS.md'), 'w').write('\n'.join(L))
    print('wrote', os.path.join(d(n), 'TRADEOFFS.md'))


if __name__ == '__main__':
    a = sys.argv[1:]
    refs = None
    if '--refs' in a:
        i = a.index('--refs'); refs = a[i + 1].split(','); del a[i:i + 2]
    if '--staging' in a:
        a.remove('--staging')
        STAGED.add(a[0])
    tradeoffs(a[0], open(a[1]).read() if len(a) > 1 else '', refs)
